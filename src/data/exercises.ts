export function getAllExercises(): Exercise[] {
  return exerciseCategories.flatMap((cat) => cat.exercises);
}

export function getExerciseById(id: string): Exercise | undefined {
  return getAllExercises().find((ex) => ex.id === id);
}

export function getExercisesByMuscleGroup(group: string): Exercise[] {
  return getAllExercises().filter((ex) => ex.muscleGroup.toLowerCase().includes(group.toLowerCase()));
}

export function getExercisesByEquipment(equipment: string): Exercise[] {
  return getAllExercises().filter((ex) => ex.equipment.toLowerCase().includes(equipment.toLowerCase()));
}

export function getExercisesByDifficulty(difficulty: string): Exercise[] {
  return getAllExercises().filter((ex) => ex.difficulty === difficulty);
}
